const supported = Object.keys(messages) as Locale[];
function detectLocale(): Locale {
  try { const saved = localStorage.getItem("fileway.locale"); if (saved && supported.includes(saved as Locale)) return saved as Locale; } catch { /* Storage may be unavailable. */ }
  const browser = navigator.language.toLowerCase().split("-")[0] as Locale;
  return supported.includes(browser) ? browser : "en";
}
let activeLocale: Locale = detectLocale();
export function getLocale(): Locale { return activeLocale; }
export function setLocale(locale: Locale): void {
  if (!supported.includes(locale)) return;
  activeLocale = locale;
  try { localStorage.setItem("fileway.locale", locale); } catch { /* Session-only preference. */ }
}
export function t(key: keyof typeof messages.en | string, replacements: Record<string, string | number> = {}): string {
  let value: string = (messages[activeLocale] as Record<string,string>)[key] ?? messages.en[key as keyof typeof messages.en] ?? key;
  for (const [name, replacement] of Object.entries(replacements)) value = value.replaceAll(`{${name}}`, String(replacement));
  return value;
}
